"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { pathToFileURL } = require("node:url");
const { chromium } = require("playwright");

(async () => {
  const browser = await chromium.launch({ headless: true, channel: process.env.TEST_BROWSER_CHANNEL || undefined });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 950 }, acceptDownloads: true });
    const errors = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.route("https://script.google.com/**", route => route.fulfill({ json: { ok: true, data: { characters: [] } } }));
    await page.goto(pathToFileURL(path.join(__dirname, "index.html")).href);
    await page.evaluate(() => window.characterSheetBuilder.tryEnterKpMode("ばに"));
    await page.locator("#map-tab").click();
    const draft = () => page.evaluate(() => window.hoshimichiAuthoring.getDrafts().maps[0]);
    assert.equal((await draft()).kind, "graph");
    await page.locator("#map-name").fill("旧採石坑");
    await page.locator("#graph-canon-id").fill("SCN-0003");
    await page.getByRole("button", { name: "+ 場所" }).click();
    await page.locator("#graph-name-0").fill("坑道入口");
    await page.locator("#graph-situation-0").fill("落石の跡がある");
    await page.getByRole("button", { name: "+ 追加", exact: true }).first().click();
    await page.locator(".graph-addition-kind").selectOption("持っていけるもの");
    await page.locator(".graph-addition-reveal").selectOption("roll");
    await page.locator(".graph-addition-row textarea").fill("壊れた箱の奥に食料がある");
    assert.deepEqual((await draft()).points[0].additions.map(({ kind, reveal, text }) => ({ kind, reveal, text })),
      [{ kind: "持っていけるもの", reveal: "roll", text: "壊れた箱の奥に食料がある" }]);
    const first = await page.locator(".graph-node-drag").first().boundingBox();
    await page.mouse.move(first.x + 75, first.y + 16); await page.mouse.down();
    await page.mouse.move(first.x - 240, first.y + 16, { steps: 7 }); await page.mouse.up();
    const moved = (await draft()).points[0];
    await page.getByRole("button", { name: "+ 場所" }).click();
    await page.locator("#graph-name-1").fill("坑道内部");
    assert.equal((await draft()).points.length, 2);
    assert((await draft()).points[0].x < (await draft()).points[1].x);
    assert((await draft()).points[0].x <= moved.x);
    assert.equal(await page.locator(".graph-port").count(), 0);
    await page.getByRole("button", { name: "接続モード" }).click();
    assert.equal(await page.locator(".graph-node").first().locator(".graph-port").count(), 8);
    await page.locator(".graph-node").first().locator('[data-port-id="right-upper"]').click();
    await page.locator(".graph-node").nth(1).locator('[data-port-id="left-upper"]').click();
    assert.equal((await draft()).routes.length, 1);
    assert.equal((await draft()).routes[0].fromPort, "right-upper");
    assert.equal((await draft()).routes[0].toPort, "left-upper");
    await page.getByRole("button", { name: "接続モード" }).click();
    assert.equal(await page.locator(".graph-port").count(), 0);
    assert.equal(await page.locator(".graph-edge").count(), 1);
    assert.equal((await draft()).routes[0].oneWay, false);
    const edge = page.locator(".graph-edge-hit");
    const details = page.locator("#graph-route-editor");
    await edge.dispatchEvent("click");
    assert.equal(await details.isHidden(), true);
    await page.keyboard.press("Delete");
    assert.equal((await draft()).routes.length, 0);
    await page.locator("#map-undo").click();
    assert.equal((await draft()).routes.length, 1);
    const timeLabel = page.locator(".graph-edge-label");
    await timeLabel.dispatchEvent("dblclick");
    assert.equal(await details.isVisible(), true);
    const placement = await page.evaluate(() => {
      const popup = document.getElementById("graph-route-editor").getBoundingClientRect();
      const label = document.querySelector(".graph-edge-label.is-selected").getBoundingClientRect();
      return { above: popup.bottom <= label.top, below: popup.top >= label.bottom };
    });
    assert(placement.above || placement.below);
    const distance = page.locator("#graph-route-distance");
    await distance.press("Delete");
    assert.equal((await draft()).routes.length, 1);
    assert.deepEqual(await page.locator(".graph-edge-label tspan").allTextContents(), ["距離未設定"]);
    await page.locator("#graph-route-condition").fill("棚を除ける必要がある");
    await distance.selectOption("50 m");
    await page.locator("#graph-route-roughness").selectOption("険しい");
    await page.locator("#graph-route-notes").fill("ぬかるんだ石畳");
    assert.equal((await draft()).routes[0].roughness, "険しい");
    assert.equal(await page.locator(".graph-edge.is-selected").getAttribute("stroke"), "#e9a15b");
    assert.deepEqual(await page.locator(".graph-edge-label tspan").allTextContents(), ["50 m", "条件あり"]);
    await page.locator("#graph-route-condition").fill("");
    assert.deepEqual(await page.locator(".graph-edge-label tspan").allTextContents(), ["50 m"]);
    await distance.selectOption({ label: "任意の距離を入力…" });
    const customDistance = page.locator("#graph-route-distance-custom");
    await customDistance.fill("125");
    await customDistance.press("Enter");
    assert.equal((await draft()).routes[0].distance, "125 m");
    assert.deepEqual(await page.locator(".graph-edge-label tspan").allTextContents(), ["125 m"]);
    await page.locator("#graph-route-condition").fill("棚を除ける必要がある");
    await page.getByRole("button", { name: "+ 人物" }).click();
    await page.locator("#graph-actor-name-0").fill("見張り");
    await page.locator("#graph-actor-kind-0").selectOption("enemy");
    await page.locator("#graph-actor-species-0").fill("ゴブリン");
    await page.locator("#graph-actor-place-0").selectOption((await draft()).points[1].id);
    assert.equal((await draft()).actors[0].initialNodeId, (await draft()).points[1].id);
    const tag = page.locator(".graph-actor-tag");
    assert.equal(await tag.count(), 1);
    assert.equal(await tag.getAttribute("data-actor-kind"), "enemy");
    assert.equal(await tag.getAttribute("title"), "見張り（敵／ゴブリン）");
    assert.equal(await tag.evaluate(node => node.closest(".graph-node").dataset.pointId), (await draft()).points[1].id);
    assert(await tag.evaluate(node => node.getBoundingClientRect().bottom < node.closest(".graph-node").getBoundingClientRect().top));
    const actorEditor = page.locator("#graph-actor-editor");
    await actorEditor.getByRole("button", { name: "閉じる" }).click();
    assert.equal(await actorEditor.isHidden(), true);
    const sourceBox = await tag.boundingBox(), targetBox = await page.locator(".graph-node").first().boundingBox();
    await page.mouse.move(sourceBox.x + sourceBox.width / 2, sourceBox.y + sourceBox.height / 2);
    await page.mouse.down();
    await page.mouse.move(targetBox.x + targetBox.width / 2, targetBox.y + targetBox.height / 2, { steps: 8 });
    assert.equal(await page.locator(".graph-node.is-actor-drop-target").count(), 1);
    await page.mouse.up();
    assert.equal((await draft()).actors[0].initialNodeId, (await draft()).points[0].id);
    assert.equal(await page.locator(".graph-actor-open-place").textContent(), "坑道入口");
    await tag.dblclick();
    assert.equal(await actorEditor.isVisible(), true);
    assert.equal(await actorEditor.locator("#graph-actor-name-0").inputValue(), "見張り");
    await actorEditor.locator("#graph-actor-place-0").selectOption((await draft()).points[1].id);
    assert.equal((await draft()).actors[0].initialNodeId, (await draft()).points[1].id);
    await actorEditor.getByRole("button", { name: "閉じる" }).click();
    const beforeDelete = await draft();
    await page.locator(".graph-node-drag").nth(1).press("Enter");
    await page.keyboard.press("Delete");
    assert.equal((await draft()).points.length, 1);
    assert.equal((await draft()).routes.length, 0);
    assert.equal((await draft()).actors[0].initialNodeId, "");
    assert.equal(await tag.count(), 0);
    await page.locator("#map-undo").click();
    assert.deepEqual(await draft(), beforeDelete);
    assert.equal(await tag.count(), 1);
    await page.locator(".graph-output summary").click();
    const output = await page.locator("#map-output").inputValue();
    for (const phrase of ["坑道入口", "落石", "食料", "棚を除ける", "見張り", "125 m", "険しさの段階：険しい", "描写：ぬかるんだ石畳"]) { assert(output.includes(phrase), phrase); }
    await page.locator(".graph-ai-panel summary").click();
    const original = await draft();
    const proposed = structuredClone(original);
    proposed.points[1].contents = "奥から音がする";
    proposed.points.push({ ...structuredClone(proposed.points[1]), id: "proposal-new-point", name: "旧資材置場", x: 1200, y: 400, eventIdeas: [] });
    await page.locator("#graph-ai-json").fill(JSON.stringify({ schema: "hoshimichi.scene-map-proposal/1", map: proposed }));
    await page.getByRole("button", { name: "案を確認" }).click();
    assert((await page.locator("#graph-ai-preview").innerText()).includes("旧資材置場"));
    page.once("dialog", dialog => dialog.accept());
    await page.locator("#graph-ai-adopt").click();
    assert.equal((await draft()).points.length, 3);
    await page.locator("#map-undo").click();
    assert.equal((await draft()).points.length, 2);
    await page.locator("#map-redo").click();
    assert.equal((await draft()).points.length, 3);
    const nodeBody = page.locator(".graph-node-body").first();
    await nodeBody.hover({ position: { x: 12, y: 12 } });
    await page.mouse.wheel(0, 120);
    await page.waitForFunction(() => document.querySelector(".graph-node-body").scrollTop > 0);
    assert.equal(await page.locator("#graph-zoom-label").innerText(), "100%");
    const viewportBox = await page.locator("#map-viewport").boundingBox();
    await page.mouse.move(viewportBox.x + 12, viewportBox.y + 12);
    await page.mouse.wheel(0, 100);
    assert.equal(await page.locator("#graph-zoom-label").innerText(), "90%");
    await page.getByRole("button", { name: "拡大" }).click();
    assert.equal(await page.locator("#graph-zoom-label").innerText(), "100%");
    const beforeZoom = await draft();
    const slider = page.getByRole("slider", { name: "MAP表示倍率" });
    await slider.fill("10");
    assert.equal(await page.locator("#graph-zoom-label").innerText(), "10%");
    const extents = await page.evaluate(() => {
      const viewport = document.getElementById("map-viewport");
      const surface = document.getElementById("graph-surface");
      return { width: surface.getBoundingClientRect().width,
        canPan: viewport.scrollWidth > viewport.clientWidth && viewport.scrollHeight > viewport.clientHeight };
    });
    assert.deepEqual(extents, { width: 280, canPan: true });
    assert.deepEqual(await draft(), beforeZoom);
    await slider.fill("100");
    await page.getByRole("button", { name: "+ 場所" }).click();
    const placed = (await draft()).points;
    const last = placed.at(-1);
    assert(placed.slice(0, -1).every(point => Math.abs(point.x - last.x) >= 280 || Math.abs(point.y - last.y) >= 260));
    if (process.env.TEST_ARTIFACT_DIR) {
      fs.mkdirSync(process.env.TEST_ARTIFACT_DIR, { recursive: true });
      for (const width of [1440, 390]) {
        await page.setViewportSize({ width, height: 950 });
        await page.locator("#map-panel").scrollIntoViewIfNeeded();
        assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
        await page.screenshot({ path: path.join(process.env.TEST_ARTIFACT_DIR, "graph-" + width + ".png") });
        if (width === 390) {
          await page.locator("#map-viewport").scrollIntoViewIfNeeded();
          await page.screenshot({ path: path.join(process.env.TEST_ARTIFACT_DIR, "graph-390-canvas.png") });
        }
      }
    }
    const received = page.waitForEvent("download");
    await page.locator("#map-panel").getByRole("button", { name: "下書きJSONを出力" }).click();
    const download = await received;
    const exported = JSON.parse(fs.readFileSync(await download.path(), "utf8"));
    assert.equal(exported.maps[0].kind, "graph");
    await page.evaluate(() => window.characterSheetBuilder.exitKpMode());
    assert.equal(await page.locator("#map-panel").innerHTML(), "");
    await page.reload();
    await page.evaluate(() => window.characterSheetBuilder.tryEnterKpMode("ばに"));
    await page.locator("#map-tab").click();
    assert.equal((await draft()).points.length, 4);
    assert.deepEqual(errors, []);
    console.log("Authoring graph: PASS (node edit, drag, link, actors, AI review, history, export, responsive, relock)");
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
