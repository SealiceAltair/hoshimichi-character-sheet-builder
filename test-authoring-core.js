"use strict";
const assert = require("node:assert/strict");
const C = require("./authoring-core.js");
let map = C.newMap("local-test");
C.rectangle(map, [2, 2], [8, 8], 0, true);
assert.equal(map.cells[2 * map.width + 2], 2);
assert.equal(map.cells[3 * map.width + 3], 1);
C.fill(map, 3, 3, 6);
assert.equal(map.cells[4 * map.width + 4], 6);
assert.equal(map.cells[0], 0);
C.paintLine(map, [0, 0], [20, 10], 3);
assert.equal(map.cells[10 * map.width + 20], 3);
assert.equal(map.cells[0], 3);
const point = (id, x, y) => Object.assign(Object.fromEntries(C.pointFields.map(k => [k, ""])), { id, x, y, name: id });
map.points = [point("p1", 3, 3), point("p2", 20, 12)];
map.points[1].possibleEnemies = "狼がいるかもしれない";
map.points[1].events = "落石・旅人との遭遇";
map.routes = [{ id: "r1", from: "p1", to: "p2", distance: "約1km", time: "20〜40分", roughness: "急坂", notes: "雨の後は増水" }];
assert.deepEqual(C.validateMap(map), map);
assert.throws(() => C.validateMap({ ...map, cells: [999] }));
assert.throws(() => C.validateMap({ ...map, width: 999 }));
assert.throws(() => C.validateMap({ ...map, points: [...map.points, map.points[0]] }));
assert.throws(() => C.validateMap({ ...map, routes: [{ ...map.routes[0], to: "missing" }] }));
const shrunk = C.resize(map, 10, 10);
assert.equal(shrunk.points.length, 1); assert.equal(shrunk.routes.length, 0);
const expanded = C.resize(map, 30, 20);
assert.equal(expanded.cells[2 * 30 + 2], map.cells[2 * 24 + 2]);
const request = C.mapRequest(map);
for (const phrase of ["20〜40分", "急坂", "落石", "候補", "確率を創作しない", "縮尺を推測しない", "1始まり"]) { assert(request.includes(phrase), phrase); }
const scenario = C.newScenario("s1"); scenario.mapIds = [map.id]; scenario.secrets = "秘密の地下通路"; scenario.tags = ["探索", "戦わずに解決"];
const store = { version: 1, maps: [map], scenarios: [scenario] };
assert.deepEqual(C.validateStore(JSON.parse(JSON.stringify(store))), store);
const before = JSON.stringify(store), text = C.scenarioText(scenario, [map]);
assert.equal(JSON.stringify(store), before);
for (const phrase of ["秘密の地下通路", "KP専用", "主KP", "採番しない", "星歴：992", "戦わずに解決", "20〜40分", "卓の開始はこの依頼には含めません"]) { assert(text.includes(phrase), phrase); }
assert.throws(() => C.validateStore({ ...store, maps: [] }));
assert.throws(() => C.validateScenario({ ...scenario, year: "not-a-year" }));
assert.throws(() => C.validateScenario({ ...scenario, canonId: "made-up" }));
assert.throws(() => C.validateStore({ ...store, version: 999 }));
const graph = C.newGraphMap("local-graph");
graph.name = "森への道"; graph.canonId = "SCN-0002";
graph.points = [{ ...point("g1", 120, 180), eventIdeas: [] }, { ...point("g2", 720, 480), eventIdeas: ["道案内に出会うかもしれない"] }];
graph.routes = [{ id: "gr1", from: "g1", to: "g2", distance: "約2km", time: "未定", roughness: "足場は要確認", notes: "", condition: "橋を架けないと通れない", oneWay: false, fromPort: "top-left", toPort: "bottom-right" }];
graph.actors = [{ id: "a1", name: "見張り", kind: "enemy", species: "ゴブリン", initialNodeId: "g2", goal: "坑道を守る" }];
assert.deepEqual(C.validateMap(graph), graph);
const withAddition = C.clone(graph);
withAddition.points[0].additions = [
  { id: "plant", kind: "植物", reveal: "roll", text: "倒木の陰に薬草が生えている" },
  { id: "lever", kind: "仕掛け", reveal: "arrival", text: "赤い取っ手がある" }
];
assert.deepEqual(C.validateMap(withAddition), withAddition);
assert(C.mapText(withAddition).includes("追加（植物／ロールで見つかる）：倒木の陰に薬草が生えている"));
assert(C.mapText(withAddition).includes("追加（仕掛け／入ると分かる）：赤い取っ手がある"));
assert(C.sceneMapPrompt(withAddition).includes("成功前は本人が知った情報へ加えない"));
const invalidAddition = C.clone(withAddition);
invalidAddition.points[0].additions[1].reveal = "unknown";
assert.throws(() => C.validateMap(invalidAddition));
invalidAddition.points[0].additions[1] = invalidAddition.points[0].additions[0];
assert.throws(() => C.validateMap(invalidAddition));
const expandedGraph = C.clone(graph);
Object.assign(expandedGraph.points[0], { x: 2540, y: 1610 });
assert.deepEqual(C.validateMap(expandedGraph), expandedGraph);
expandedGraph.points[0].x++;
assert.throws(() => C.validateMap(expandedGraph));
assert.deepEqual(C.validateStore({ version: 1, maps: [map, graph], scenarios: [scenario] }).maps[1], graph);
assert.throws(() => C.validateMap({ ...graph, points: [{ ...graph.points[0], x: 5000 }] }));
assert.throws(() => C.validateMap({ ...graph, kind: "unknown" }));
assert.throws(() => C.validateMap({ ...graph, actors: [{ ...graph.actors[0], initialNodeId: "missing" }] }));
const graphText = C.mapRequest(graph);
assert(graphText.includes("険しさの段階：未設定"));
assert(graphText.includes("以前の険しさ欄（参考）：足場は要確認"));
assert.equal(C.routeRoughnessLevel("悪路").name, "険しい");
assert.equal(C.routeRoughnessLevel("険しい").color, C.routeRoughnessLevel("悪路").color);
assert.equal(C.routeRoughnessLevel("ぬかるんだ石畳"), undefined);
const customTerrain = { ...graph, routes: [{ ...graph.routes[0], roughness: "険しい", notes: "ぬかるんだ石畳" }] };
assert.deepEqual(C.validateMap(customTerrain), customTerrain);
assert(C.mapText(customTerrain).includes("描写：ぬかるんだ石畳"));
for (const phrase of ["場所ノードMAP", "線の長さは実距離", "約2km", "候補", "道案内に出会うかもしれない", "見張り", "橋を架けないと通れない"]) { assert(graphText.includes(phrase), phrase); }
assert.equal(C.hasRequiredPassageCondition(""), false);
assert.equal(C.hasRequiredPassageCondition("なし"), false);
assert.equal(C.hasRequiredPassageCondition("条件なし"), false);
assert.equal(C.hasRequiredPassageCondition("橋を架けないと通れない"), true);
assert(C.mapText({ ...graph, routes: [{ ...graph.routes[0], condition: "なし" }] }).includes("通行条件：なし"));
assert(!graphText.includes("1マスの距離"));
assert(C.scenarioText({ ...scenario, mapIds: [graph.id] }, [graph]).includes("場所ノードMAP"));
const prompt = C.sceneMapPrompt(graph);
assert(prompt.includes("hoshimichi.scene-map-proposal/1"));
assert(prompt.includes("橋を架けないと通れない"));
assert(prompt.includes("街道・森・急斜面などは段階の例"));
assert(prompt.includes("notes（描写）へ自由に記す"));
assert.deepEqual(C.validateSceneMapProposal({ schema: "hoshimichi.scene-map-proposal/1", map: graph }, graph), graph);
assert.throws(() => C.validateSceneMapProposal({ schema: "hoshimichi.scene-map-proposal/1", map: { ...graph, id: "other" } }, graph));
const legacyGraph = { ...graph, actors: undefined, points: graph.points.map(({ eventIdeas, ...rest }) => rest), routes: graph.routes.map(({ condition, oneWay, fromPort, toPort, ...rest }) => rest) };
assert.deepEqual(C.validateMap(legacyGraph).points[1].eventIdeas, []);
const migrated = C.validateMap(legacyGraph);
assert.equal(migrated.routes[0].oneWay, false);
assert.deepEqual([migrated.routes[0].fromPort, migrated.routes[0].toPort], ["right-upper", "left-upper"]);
assert.equal(Object.keys(C.graphPorts).length, 8);
const moved = C.clone(graph);
moved.points[0].x = 1000;
const reloaded = C.validateMap(JSON.parse(JSON.stringify(moved)));
assert.deepEqual(reloaded.routes, graph.routes);
assert.deepEqual(C.graphAnchor(reloaded.points[0], reloaded.routes[0].fromPort),
  { x: 1087, y: 180, nx: 0, ny: -1 });
assert.throws(() => C.validateMap({ ...graph, routes: [{ ...graph.routes[0], fromPort: "constructor" }] }));
const proposalWithoutPorts = { schema: "hoshimichi.scene-map-proposal/1", map: { ...moved, routes: legacyGraph.routes } };
assert.equal(C.validateSceneMapProposal(proposalWithoutPorts, graph).routes[0].fromPort, "top-left");
console.log("Authoring core: PASS (legacy grid, scenario graph, validation, AI proposal, text export)");
